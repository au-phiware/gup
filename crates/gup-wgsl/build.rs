//! Lists Gup's WGSL library (`library/*.wgsl`) for
//! `gup_wgsl::compose::library` (GUP-420): one `include_str!` per file,
//! so the text is compiled into this crate and both of its build-time
//! consumers (gup-core's build script and `#[wgsl_function]`) see the same
//! sources. Adding a module is adding a file.

use std::fmt::Write as _;
use std::path::PathBuf;

fn main() {
    println!("cargo::rerun-if-changed=library");
    let manifest = PathBuf::from(std::env::var("CARGO_MANIFEST_DIR").expect("set by cargo"));
    let dir = manifest.join("library");
    let mut files: Vec<String> = std::fs::read_dir(&dir)
        .unwrap_or_else(|e| panic!("{}: {e}", dir.display()))
        .map(|e| e.expect("a directory entry").file_name())
        .map(|n| n.to_string_lossy().into_owned())
        .filter(|n| n.ends_with(".wgsl"))
        .collect();
    files.sort();
    let mut rs = String::from("// Generated by gup-wgsl's build.rs; do not edit.\n&[\n");
    for f in files {
        let _ = writeln!(
            rs,
            "    (\"gup-wgsl/library/{f}\", include_str!(concat!(env!(\"CARGO_MANIFEST_DIR\"), \"/library/{f}\"))),"
        );
    }
    rs.push_str("]\n");
    let out = PathBuf::from(std::env::var("OUT_DIR").expect("set by cargo"));
    std::fs::write(out.join("library.rs"), rs).expect("writing library.rs");
}
